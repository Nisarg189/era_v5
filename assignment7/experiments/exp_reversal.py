"""
Experiment C and D: the head is the codec run backwards, and it needs no vocabulary.

A tied-Kronecker model is trained, then three things are shown.

C1 (the head is an adjoint, not a matrix). The tied head's logits are exactly
    q @ C^T  where  q = H @ W_in^T  is the "query code" the hidden state projects to
    and C are the fixed byte codes. There is no V x D parameter anywhere: prediction
    is the dot product of a query code against codes generated on the fly, i.e. nearest
    code, and the codec inverts a code back to its token string. This is the reverse of
    the forward path token -> code -> embedding.

C2 (decoding without a stored head). Text is generated by scoring the query code
    against candidate codes, never materialising a V x D matrix.

D  (a 1,000,000-token vocabulary costs nothing extra). The candidate set is expanded
    with thousands of tokens the model never trained on. Prediction accuracy holds, the
    head gains zero parameters, and the model assigns higher probability to real unseen
    words than to random byte strings, i.e. it scores tokens it has never seen. A dense
    head cannot score any of them, because it has no row for a token it never allocated.
"""

import json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from rkron.data import make_streams, get_batch
from rkron.model import TinyLM
from rkron.train import train_model, evaluate
from rkron.codec import KroneckerCodec

_HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(_HERE, "artifacts")


def _resolve_vocab():
    for c in ["/root/a7/data/vocab.json",
              "/mnt/user-data/uploads/assignments/webapp/assignment2/tokenizer/vocab.json",
              os.path.join(_HERE, "..", "..", "webapp", "assignment2", "tokenizer", "vocab.json")]:
        if os.path.isfile(c):
            return c
    return c


A2_VOCAB = _resolve_vocab()
os.makedirs(OUT, exist_ok=True)


def softmax_rows(z):
    z = z - z.max(axis=-1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=-1, keepdims=True)


def main():
    res = {}
    data = make_streams(target_vocab=1200, max_chars_per_lane=300000, seed=0)
    V = len(data["vocab"])
    stoi = data["stoi"]
    codec = KroneckerCodec()

    print("training a tied-Kronecker model for the reversal demos ...")
    m = TinyLM(data["vocab"], d_model=96, block_size=48, n_layer=2,
               input_path="kron", head="tied_kron", seed=0)
    train_model(m, data, steps=500, lr=1e-3, batch=24, block=48, eval_every=250, seed=0)
    final = evaluate(m, data["val"], 48, n_batches=30)
    res["trained_val"] = final
    print(f"trained val loss {final['loss']:.3f}  acc {final['acc']:.3f}")

    # ---- C1: logits are exactly q @ C^T (the head is the codec adjoint) ----
    x, y = get_batch(data["val"], 8, 48, np.random.default_rng(7))
    logits, H = m.forward(x)                      # H: [B,T,D]
    E = (m.C @ m.W_in).data                       # [V,D], the tied embedding
    q = H.data @ m.W_in.data.T                    # [B,T,8192] query code
    logits_via_code = (q @ m.C.data.T) * m.logit_scale.data
    max_diff = float(np.abs(logits.data - logits_via_code).max())
    res["adjoint_identity_max_abs_diff"] = max_diff
    print(f"C1  max|logits - q@C^T| = {max_diff:.2e}  (head carries no V x D matrix)")

    # ---- C2: generate by nearest-code, no stored head ----
    def generate(prompt, n=60, temp=0.8, seed=0):
        rng = np.random.default_rng(seed)
        from rkron.data import encode
        ids = encode(prompt, stoi)[-48:]
        if not ids:
            ids = [stoi.get(" ", 0)]
        out = list(ids)
        for _ in range(n):
            ctx = np.array([out[-48:]])
            pad = 48 - ctx.shape[1]
            if pad > 0:
                ctx = np.concatenate([np.zeros((1, pad), int), ctx], axis=1)
            lg, _ = m.forward(ctx)
            p = softmax_rows(lg.data[0, -1] / temp)
            nxt = int(rng.choice(len(p), p=p))
            out.append(nxt)
        return "".join(data["vocab"][i] for i in out)

    samples = {p: generate(p, seed=i) for i, p in enumerate(["भारत ", "The ", "def "])}
    res["generation_samples"] = samples
    for k, v in samples.items():
        print(f"C2  gen[{k!r}]: {v!r}")

    # ---- D: expand the candidate vocabulary with unseen real tokens ----
    a2 = json.load(open(A2_VOCAB, encoding="utf-8"))
    a2_tokens = list(a2.keys()) if isinstance(a2, dict) else list(a2)
    unseen = [t for t in a2_tokens
              if t not in stoi and len(t.encode("utf-8")) <= 32 and len(t) > 0]
    rng = np.random.default_rng(0)
    rng.shuffle(unseen)

    def acc_with_candidates(extra):
        # candidate order: the V training tokens first (ids stay valid), then unseen
        cand = list(data["vocab"]) + extra
        C = codec.encode_batch(cand)              # [Vc, 8192], generated on the fly
        r = np.random.default_rng(99)
        accs = []
        for _ in range(8):
            x, y = get_batch(data["val"], 16, 48, r)
            _, H = m.forward(x)
            q = H.data @ m.W_in.data.T
            lg = (q @ C.T) * m.logit_scale.data    # [B,T,Vc]
            pred = lg.reshape(-1, lg.shape[-1]).argmax(-1)
            accs.append((pred == y.reshape(-1)).mean())
        return float(np.mean(accs)), len(cand)

    scaling = []
    for k in [0, 1000, 3000, min(6000, len(unseen))]:
        a, vc = acc_with_candidates(unseen[:k])
        scaling.append({"candidates": vc, "unseen_added": k, "val_top1_acc": a,
                        "head_params_added": 0})
        print(f"D   candidates={vc:6d}  (+{k} unseen)  val_top1_acc={a:.4f}  head_params_added=0")
    res["candidate_scaling"] = scaling

    # ---- D: zero-shot scoring of unseen tokens, real words vs gibberish ----
    def mean_logprob_over(context, cand_tokens):
        from rkron.data import encode
        ids = encode(context, stoi)[-48:]
        if len(ids) < 48:
            ids = [0] * (48 - len(ids)) + ids
        _, H = m.forward(np.array([ids]))
        q = H.data[0, -1] @ m.W_in.data.T
        allc = list(data["vocab"]) + cand_tokens
        C = codec.encode_batch(allc)
        p = softmax_rows((q @ C.T) * m.logit_scale.data)
        # probability mass placed on the appended (unseen) candidates
        return float(p[V:].sum()), float(np.log(p[V:] + 1e-12).mean())

    # unseen real Devanagari words vs random 3-byte-char gibberish of similar length
    real_hi = [t for t in unseen if any(0x900 <= ord(c) <= 0x97F for c in t)][:40]
    gib = []
    for _ in range(40):
        L = rng.integers(2, 6)
        gib.append("".join(chr(int(rng.integers(0x900, 0x97F))) for _ in range(L)))
    mass_real, lp_real = mean_logprob_over("भारत एक ", real_hi)
    mass_gib, lp_gib = mean_logprob_over("भारत एक ", gib)
    res["open_vocab_zero_shot"] = {
        "context": "भारत एक ",
        "n_real_unseen": len(real_hi), "n_gibberish": len(gib),
        "mean_logprob_real_unseen": lp_real,
        "mean_logprob_gibberish": lp_gib,
        "prob_mass_real_unseen": mass_real,
        "prob_mass_gibberish": mass_gib,
    }
    print(f"D   zero-shot: mean logprob real-unseen {lp_real:.3f} vs gibberish {lp_gib:.3f}")

    with open(os.path.join(OUT, "reversal.json"), "w") as f:
        json.dump(res, f, indent=2, ensure_ascii=False)
    print("-> artifacts/reversal.json")


if __name__ == "__main__":
    main()
